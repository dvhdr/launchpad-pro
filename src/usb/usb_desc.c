/*
 * USB descriptors for the MIDI 2.0 device (stage 1).
 *
 * Alt setting 0 of the MIDIStreaming interface is the original USB MIDI 1.0
 * descriptor set, byte for byte (only wTotalLength changes). Alt setting 1
 * adds the USB MIDI 2.0 (UMP) endpoints and Group Terminal Blocks.
 */
#include "usb/usb_desc.h"

/* original bytes 9..132 of the configuration descriptor (after the header) */
#define USB_ALT0_BODY \
	0x09, 0x04, 0x00, 0x00, 0x00, 0x01, 0x01, 0x00, 0x02, 0x09, 0x24, 0x01, \
	0x00, 0x01, 0x09, 0x00, 0x01, 0x01, 0x09, 0x04, 0x01, 0x00, 0x02, 0x01, \
	0x03, 0x00, 0x02, 0x07, 0x24, 0x01, 0x00, 0x01, 0x43, 0x00, 0x06, 0x24, \
	0x02, 0x01, 0x01, 0x04, 0x06, 0x24, 0x02, 0x02, 0x02, 0x04, 0x09, 0x24, \
	0x03, 0x01, 0x09, 0x01, 0x02, 0x01, 0x04, 0x09, 0x24, 0x03, 0x02, 0x0A, \
	0x01, 0x01, 0x01, 0x04, 0x06, 0x24, 0x02, 0x01, 0x03, 0x05, 0x06, 0x24, \
	0x02, 0x02, 0x04, 0x05, 0x09, 0x24, 0x03, 0x01, 0x0B, 0x01, 0x04, 0x01, \
	0x05, 0x09, 0x24, 0x03, 0x02, 0x0C, 0x01, 0x03, 0x01, 0x05, 0x09, 0x05, \
	0x01, 0x02, 0x40, 0x00, 0x00, 0x00, 0x00, 0x06, 0x25, 0x01, 0x02, 0x01, \
	0x03, 0x09, 0x05, 0x81, 0x02, 0x40, 0x00, 0x00, 0x00, 0x00, 0x06, 0x25, \
	0x01, 0x02, 0x09, 0x0B

#define USB_ALT1_BLOCK \
	0x09, 0x04, 0x01, 0x01, 0x02, 0x01, 0x03, 0x00, 0x00, \
	0x07, 0x24, 0x01, 0x00, 0x02, 0x07, 0x00, \
	0x07, 0x05, 0x01, 0x02, 0x40, 0x00, 0x00, \
	0x06, 0x25, 0x02, 0x02, 0x01, 0x02, \
	0x07, 0x05, 0x81, 0x02, 0x40, 0x00, 0x00, \
	0x06, 0x25, 0x02, 0x02, 0x01, 0x02

#define USB_CONFIG_HEADER(power) \
	0x09, 0x02, 0xAF, 0x00, 0x02, 0x01, 0x00, 0x80, (power)

const uint8_t usb_device_desc[18] = {USB_DEVICE_DESC_BYTES};

const uint8_t usb_config_desc_bus[USB_CONFIG_DESC_LEN] = {
	USB_CONFIG_HEADER(0xFA),
	USB_ALT0_BODY,
	USB_ALT1_BLOCK
};

const uint8_t usb_config_desc_psu[USB_CONFIG_DESC_LEN] = {
	USB_CONFIG_HEADER(0x01),
	USB_ALT0_BODY,
	USB_ALT1_BLOCK
};

const uint8_t usb_gtb_desc[31] = {
	/* header, wTotalLength 31 */
	0x05, 0x26, 0x01, 0x1F, 0x00,
	/* block 1: bidirectional, group 0, 1 group, iBlockItem 4, MIDI 2.0 */
	0x0D, 0x26, 0x02, 0x01, 0x00, 0x00, 0x01, 0x04, 0x11, 0x00, 0x00, 0x00, 0x00,
	/* block 2: bidirectional, group 1, 1 group, iBlockItem 5, MIDI 1.0 <=128 bit */
	0x0D, 0x26, 0x02, 0x02, 0x00, 0x01, 0x01, 0x05, 0x03, 0x01, 0x00, 0x01, 0x00
};
